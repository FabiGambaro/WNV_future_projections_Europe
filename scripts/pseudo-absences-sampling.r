#load sp data
nutsM <- readRDS("WNV/Processed_data/nutsM_EU.rds")
nutsM_sf<- readRDS("WNV/Processed_data/nutsM_sf.rds") #with new Serbian, Croatian and Kosovo NUTS3 codes from script Europe_NUTS3_shapefile_prep
nutsM_IDs<- read_tsv("WNV/Processed_data/nutsM_IDs.tsv")
contour_sf <- st_union(nutsM_sf)

#load presence data
presences_data <- read_csv("WNV/Occurrence_data/wnv_presences_nutsM_year.csv") #1087
presences_nutsM <- nutsM_sf[nutsM_sf$LocationCo %in% presences_data$nutsM_code,]

#aggregate years of presences for each NUTS3.
source("WNV/helper_functions/years_by_NUTS3.r")
presences_agg<-years_by_nuts(presences_data) #261
presences_agg$response = 1 


## pseudo-absence stategy: surveillance capacity + exclusion of 2025 + 2026 presence locations NUTS3 ##

#pseudo-absences will be randomly generated by sampling across the study area, excluding presence 
#locations (2008-2024) + 2025 + 2026 presence locations and their neighbours,
#and preferentially from regions with a minimum surveillance capacity threshold from estimates by Lim et al. (2025)

source("WNV/helper_functions/pseudo_absences_shp.r")
pseudo_absences_nutsM <- pseudo_absences_shp(presences_agg, nutsM_sf)

to_exclude <- read_tsv("WNV/Occurrence_data/excluded_2025-26_data.tsv")
to_exclude <- to_exclude[,2]
to_exclude$year <- rep(NA, nrow(to_exclude))
to_exclude$year_start <- rep(NA, nrow(to_exclude))
to_exclude$year_end <- rep(NA, nrow(to_exclude))
to_exclude$response <- rep(1, nrow(to_exclude))

#add excluded areas (NUST3 where we have cases in 2025 and 2026) to presences_agg. 
#the function will randomly sample pseudo-abscenses from the study area excluding presence locations and neighbours.
presences_excluded_areas <- rbind(presences_agg, to_exclude)#388
pseudo_absences_excluded_nutsM <- pseudo_absences_shp(presences_excluded_areas, nutsM_sf)

#now subsample pseudoabsences to a ratio 1:1 according surveillance capacity
pseudo_absences_surv <- surv.nutsM_data[surv.nutsM_data$nutsM_code %in% pseudo_absences_excluded_nutsM$LocationCo,]
pseudo_absences_surv$prob <- pseudo_absences_surv$surv/sum(pseudo_absences_surv$surv) #weighted prob

#We assign to the pseudo-absences the distribution of the presence data, not 2025-2026.
#pseudo-absences must be assigned to a specific year or range year,as the model is trained temporally. 
#sampling pseudo years from the presences row, given either a year or a range-year. In this way, they have the same smoothing effect from the averaging.
#each pseudo-absence copies the time setup of one randomly drawn presence row

#generating pseudo-absences
data_train <- list()
n.iterations = 100 ; set.seed(113)
n_pseudo <- nrow(presences_agg); ratio = 1
for(i in 1:n.iterations){
  indices <- pseudo_absences_surv$nutsM_code
  pseudo_absences_codes <- sample(indices, ratio*n_pseudo, replace = F, prob = pseudo_absences_surv$prob) #sample NUTS3 codes without replacement, weighted by surveillance
  pseudo_absences_sampled <- pseudo_absences_surv[pseudo_absences_surv$nutsM_code %in% pseudo_absences_codes, ]
  pseudo_absences <- pseudo_absences_sampled[,"nutsM_code"]
  w <- sample(nrow(presences_agg), n_pseudo, replace = TRUE)
  pseudo_absences$year_start<- presences_agg$year_start[w]
  pseudo_absences$year_end<- presences_agg$year_end[w]
  pseudo_absences$year<- presences_agg$year[w]
  pseudo_absences$response = 0
  data <- rbind(presences_agg, pseudo_absences) #merge data
  data_train[[i]] <- data
}
saveRDS(data_train, "WNV/Output/presence_pseudoabsences_STG2.rds")

pdf("WNV/Figures/presence_pseudoabsences_STG2.pdf", width=10, height=10)
plot_list <-list()
for (i in 1:16){
  pseudo_absences_sampled <- data_train[[i]][which(data_train[[i]]$response == 0),]
  pseudo_absences_nutsM = nutsM_sf %>% filter(LocationCo %in% pseudo_absences_sampled$nutsM_code)
  plot <- ggplot() +
    geom_sf(data=contour_sf, fill = NA, color = "gray30", size = 0.4) +
    geom_sf(data=nutsM_sf, fill = "gray95", color = "gray50", size = 0.1) +
    geom_sf(data=presences_nutsM, fill = "#D73027", color = "gray50", size = 0.1) +
    geom_sf(data=pseudo_absences_nutsM, fill = "blue", color = "gray50", size = 0.1) +
    theme_bw()
  plot_list[[i]] <-plot
}
cowplot::plot_grid(plotlist = plot_list, ncol = 4, nrow = 4, align = "hv")
dev.off()
